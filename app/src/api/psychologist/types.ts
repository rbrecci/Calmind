export type PageParams = { page?: number; per_page?: number };
export type Page<T> = { data: T[]; meta: { total: number; page: number; per_page: number } };
export type Person = { id: number; name: string };
export type Profile = {
  id: number | null;
  crp: string | null;
  approval_status: 'not_submitted' | 'pending' | 'approved' | 'rejected';
  approval_note: string | null;
  profile_approach: string | null;
  profile_specialty: string | null;
  profile_modality: 'online' | 'presencial' | 'ambos' | null;
  profile_region: string | null;
  profile_bio: string | null;
  profile_published_at: string | null;
};
export type ProfileInput = Partial<Pick<Profile, 'profile_approach' | 'profile_specialty' | 'profile_modality' | 'profile_region' | 'profile_bio'>>;
export type DocumentUpload = { uri: string; name: string; mimeType?: string; size?: number; file?: File };
export type RegistrationInput = { crp_region: string; crp_number: string; document: DocumentUpload };
export type PatientSummary = {
  bond_id: number;
  status: 'active' | 'ended';
  since: string;
  ended_at: string | null;
  patient: Person;
  unread_messages: number;
  overdue_tasks: number;
  next_appointment_at: string | null;
};
export type PatientDetail = {
  bond_id: number;
  bond_status: 'active' | 'ended';
  since: string;
  patient: Person;
  is_minor: boolean;
  guardian: { name: string; phone: string; relationship: string } | null;
};
export type BondRequest = { id: number; status: 'pending'; origin: 'catalog' | 'invitation'; requested_at: string; patient: Person };
export type Bond = {
  id: number;
  status: 'pending' | 'active' | 'ended';
  origin: 'catalog' | 'invitation';
  psychologist_id: number;
  patient_user_id: number;
  requested_at: string;
  responded_at: string | null;
  ended_at: string | null;
};
export type Invitation = { id: number; code: string; expires_at: string; created_at: string };
export type RevokedInvitation = Omit<Invitation, 'created_at'> & { revoked_at: string };
export type SharedReport = { id: number; body: string; created_at: string };
export type Task = {
  id: number;
  bond_id: number;
  title: string;
  description: string | null;
  due_date: string | null;
  status: 'pending' | 'completed';
  completed_at: string | null;
  created_at: string;
};
export type TaskInput = { bond_id: number; title: string; description?: string | null; due_date: string };
export type TaskUpdate = Partial<Omit<TaskInput, 'bond_id'>>;
export type Message = { id: number; bond_id: number; sender_user_id: number; mine: boolean; body: string; sent_at: string; read_at: string | null };
export type Appointment = {
  id: number;
  bond_id: number;
  scheduled_at: string;
  status: 'scheduled' | 'rescheduled' | 'cancelled' | 'done';
  modality: 'online' | 'presencial' | null;
  notes: string | null;
  created_at: string;
  patient: Person;
};
export type AppointmentInput = { bond_id: number; scheduled_at: string; modality?: Appointment['modality']; notes?: string | null; confirm_conflict?: boolean };
export type AppointmentUpdate = Partial<Omit<AppointmentInput, 'bond_id'>>;
export type AppointmentParams = PageParams & { bond_id?: number; from?: string; to?: string };
export type Notification = { id: number; type: string; resource_id: number; created_at: string; read_at: string | null };
export type ConsentTerm = { id: number; type: 'general'; version: string; body: string; effective_from: string; accepted: boolean };
export type ConsentAcceptance = { id: number; consent_term_id: number; type: 'general'; version: string; accepted_at: string; revoked_at: string | null };
export type GuardianConsentInput = { guardian_name: string; obtained_at: string; method: 'presencial' | 'telefone' | 'videochamada' | 'mensagem_escrita'; note?: string | null };
export type GuardianConsent = GuardianConsentInput & { id: number; note: string | null; consent_term_id: number; registered_by_user_id: number; created_at: string };
export type MockScenario = 'com-pacientes' | 'sem-pacientes' | 'cadastro-nao-enviado' | 'cadastro-pendente' | 'cadastro-recusado';

export type PsychologistApi = {
  profile(): Promise<Profile>;
  updateProfile(input: ProfileInput): Promise<Profile>;
  publishProfile(): Promise<Profile>;
  submitRegistration(input: RegistrationInput): Promise<Profile>;
  patients(params?: PageParams & { status?: 'active' | 'ended' }): Promise<Page<PatientSummary>>;
  patient(id: number): Promise<PatientDetail>;
  bondRequests(params?: PageParams): Promise<Page<BondRequest>>;
  acceptBondRequest(id: number): Promise<Bond>;
  rejectBondRequest(id: number): Promise<Bond>;
  createInvitation(): Promise<Invitation>;
  revokeInvitation(id: number): Promise<RevokedInvitation>;
  endBond(id: number): Promise<Bond>;
  reports(patientId: number, params?: PageParams): Promise<Page<SharedReport>>;
  tasks(params?: PageParams & { bond_id?: number }): Promise<Page<Task>>;
  createTask(input: TaskInput): Promise<Task>;
  updateTask(id: number, input: TaskUpdate): Promise<Task>;
  archiveTask(id: number): Promise<{ message: string }>;
  messages(bondId: number, params?: PageParams & { after_id?: number }): Promise<Page<Message>>;
  sendMessage(bondId: number, body: string): Promise<Message>;
  readMessages(bondId: number): Promise<{ read: number }>;
  appointments(params?: AppointmentParams): Promise<Page<Appointment>>;
  createAppointment(input: AppointmentInput): Promise<Appointment>;
  updateAppointment(id: number, input: AppointmentUpdate): Promise<Appointment>;
  cancelAppointment(id: number): Promise<Appointment>;
  notifications(params?: PageParams & { unread?: 1 }): Promise<Page<Notification>>;
  readNotification(id: number): Promise<Notification>;
  readAllNotifications(): Promise<{ read: number }>;
  currentConsent(): Promise<ConsentTerm>;
  acceptConsent(termId: number): Promise<ConsentAcceptance>;
  guardianConsents(patientId: number, params?: PageParams): Promise<Page<GuardianConsent>>;
  createGuardianConsent(patientId: number, input: GuardianConsentInput): Promise<GuardianConsent>;
};
